import { z } from 'zod';
import { COUNTRIES, GENDERS, LANGUAGES } from '@paperwork/types';

export const signInSchema = z.object({
    body: z.object({
        email: z
            .string()
            .trim()
            .email('Invalid email format')
            .transform((value) => value.toLowerCase()),

        password: z.string().min(1, 'Password is required'),
    }),
});

export const signUpSchema = z.object({
    body: z.object({
        email: z
            .string()
            .trim()
            .email('Invalid email format')
            .max(254, 'Email too long')
            .transform((value) => value.toLowerCase()),
        password: z
            .string()
            .min(8, 'Password must be at least 8 characters long')
            .max(128, 'Password cannot exceed 128 characters'),
        fullName: z
            .string()
            .trim()
            .min(2, 'Full name must be at least 2 characters long')
            .max(100, 'Full name cannot exceed 100 characters'),
    }),
});

export const validateEmailSchema = z.object({
    body: z.object({
        email: z
            .string()
            .trim()
            .email('Invalid email format')
            .transform((value) => value.toLowerCase()),
    }),
});

export const accountActionsSchema = z.object({
    body: z.object({
        action: z.enum(
            [
                'delete-account',
                'enable-2fa',
                'disable-2fa',
                'deactivate-account',
            ],
            {
                message: 'Invalid API',
            }
        ),
        password: z
            .string()
            .min(1, 'Invalid API')
            .max(128, 'Password too long'),
    }),
});

/** Six-digit numeric OTP, as generated by `otp.service`. */
const otpSchema = z
    .string()
    .trim()
    .regex(/^\d{6}$/, 'Invalid or expired OTP. Please try again.');

export const verifyEmailSchema = z.object({
    body: z.object({
        otp: otpSchema,
    }),
});

export const twoFactorVerifySchema = z.object({
    params: z.object({
        otp: otpSchema,
    }),
});

export const changePasswordSchema = z.object({
    body: z.object({
        currentPassword: z.string().min(1, 'Current password is required').max(128),
        newPassword: z
            .string()
            .min(8, 'New password must be at least 8 characters long')
            .max(128, 'Password cannot exceed 128 characters'),
    }),
});

export const resetPasswordBodySchema = z.object({
    body: z.object({
        newPassword: z
            .string()
            .min(8, 'New password must be at least 8 characters long')
            .max(128, 'Password cannot exceed 128 characters'),
    }),
});

export const SecuritySettingsSchema = z.object({
    body: z.object({
        dob: z
            .string()
            .refine((date) => !isNaN(Date.parse(date)), {
                message: 'Invalid date format',
            })
            .refine((date) => new Date(date) <= new Date(), {
                message: 'Date of birth cannot be in the future',
            }),
        gender: z.enum(Object.values(GENDERS), {
            message: 'Invalid gender value',
        }),
        country: z.enum(Object.values(COUNTRIES), {
            message: 'Invalid country value',
        }),
        language: z.enum(Object.values(LANGUAGES), {
            message: 'Invalid language value',
        }),
    }),
});

export const UpdateSecuritySettingsSchema = z.object({
    body: SecuritySettingsSchema.shape.body.partial(),
});

export const profileUpdateSchema = z.object({
    body: z.object({
        fullName: z
            .string()
            .trim()
            .min(2, 'Full name must be at least 2 characters long')
            .max(100, 'Full name cannot exceed 100 characters')
            .optional(),
        bio: z.string().trim().max(500, 'Bio cannot exceed 500 characters').optional(),
        avatarUrl: z
            .string()
            .url('Invalid URL format')
            .max(2048, 'URL too long')
            .refine((u) => u.startsWith('https://') || u.startsWith('randomuser:'), {
                message: 'Avatar URL must be https or generated avatar',
            })
            .optional(),
    }),
});
